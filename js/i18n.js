class LangManagerClass {
  constructor() {
    this.storageKey = 'ari_portfolio_lang';
    this.currentLang = 'id';
    this.listeners = [];
    this.initialized = false;
    this.eventsBound = false;
  }

  init() {
    if (this.initialized) {
      this.applyLanguage();
      return;
    }
    this.initialized = true;

    try {
      const saved = localStorage.getItem(this.storageKey);
      if (saved && (saved === 'id' || saved === 'en' || saved === 'jp')) {
        this.currentLang = saved;
      } else {
        const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
        if (navLang.startsWith('ja')) {
          this.currentLang = 'jp';
        } else if (navLang.startsWith('en')) {
          this.currentLang = 'en';
        } else {
          this.currentLang = 'id';
        }
      }
    } catch (e) {
      this.currentLang = 'id';
    }

    this.applyLanguage();
    this.bindEvents();
  }

  t(key, fallback = '') {
    const dict = I18N[this.currentLang] || I18N['id'];
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    if (I18N['id'] && I18N['id'][key] !== undefined) {
      return I18N['id'][key];
    }
    return fallback || key;
  }

  setLang(lang) {
    if (!['id', 'en', 'jp'].includes(lang)) return;
    this.currentLang = lang;
    try {
      localStorage.setItem(this.storageKey, lang);
    } catch (e) {}
    this.applyLanguage();
    this.notifyListeners(lang);
  }

  getLang() {
    return this.currentLang;
  }

  onChange(callback) {
    if (typeof callback === 'function') {
      this.listeners.push(callback);
    }
  }

  notifyListeners(lang) {
    this.listeners.forEach(fn => {
      try { fn(lang); } catch (e) { console.error('Lang listener error:', e); }
    });
  }

  applyLanguage() {
    const lang = this.currentLang;
    const dict = I18N[lang] || I18N['id'];

    // 1. Text elements [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    // 2. HTML elements [data-i18n-html]
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    // 3. Placeholders [data-i18n-placeholder]
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 4. Titles / tooltips [data-i18n-title]
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key] !== undefined) {
        el.setAttribute('title', dict[key]);
      }
    });

    // 5. Aria Labels [data-i18n-aria-label]
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria-label');
      if (dict[key] !== undefined) {
        el.setAttribute('aria-label', dict[key]);
      }
    });

    // 6. Update HTML lang attribute
    document.documentElement.lang = lang === 'jp' ? 'ja' : lang;

    // 7. Update active states on switcher buttons
    document.querySelectorAll('.lang-switcher-btn').forEach(btn => {
      const btnLang = btn.getAttribute('data-lang');
      if (btnLang === lang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // 8. Update Quick Spec buttons text based on current state
    document.querySelectorAll('.btn-toggle-spec').forEach(btn => {
      const targetId = btn.getAttribute('data-target');
      const panel = document.getElementById(targetId);
      if (panel && panel.classList.contains('open')) {
        btn.textContent = dict['projects_spec_hide'] || '[ - HIDE SYSTEM SPEC ]';
      } else {
        btn.textContent = dict['projects_spec_toggle'] || '[ + QUICK SYSTEM SPEC ]';
      }
    });
  }

  bindEvents() {
    if (this.eventsBound) return;
    this.eventsBound = true;

    // Event delegation on document ensures all present and future switcher buttons work reliably
    document.addEventListener('click', (e) => {
      const btn = e.target.closest('.lang-switcher-btn');
      if (btn) {
        e.preventDefault();
        e.stopPropagation();
        const targetLang = btn.getAttribute('data-lang');
        if (targetLang && targetLang !== this.currentLang) {
          this.setLang(targetLang);
          try {
            if (typeof playMechaBeep === 'function') {
              playMechaBeep(920, 0.04);
            }
          } catch (err) {}
        }
      }
    });
  }
}

// Global instance
const LangManager = new LangManagerClass();

// Explicitly attach to window object for global script access
window.I18N = I18N;
window.LangManager = LangManager;

// Auto-initialize when DOM is ready or immediately if already loaded
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    LangManager.init();
  });
} else {
  LangManager.init();
}
